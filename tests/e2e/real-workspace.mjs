// First-run setup + unconfigured platform → "Data unavailable" (never mock numbers).
import { chromium } from "@playwright/test";
const out = process.argv[2];
const base = process.env.BASE ?? "http://localhost:3000";
const b = await chromium.launch({ executablePath: process.env.CHROMIUM ?? "/opt/pw-browsers/chromium" });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message.slice(0, 160)));
await p.goto(`${base}/login`);
await p.getByText("Set up Pulse").waitFor();
await p.screenshot({ path: `${out}/real_0_setup.png` });
await p.fill("#name", "Alex Kim");
await p.fill("#email", "alex@example.com");
await p.fill("#password", "correct-horse-battery");
await p.fill("#workspace", "Acme Apps");
await p.click("button[type=submit]");
await p.waitForURL((u) => u.pathname === "/");
await p.getByText("No apps yet").waitFor();
await p.screenshot({ path: `${out}/real_1_empty.png` });
console.log("• setup → empty state");
await p.getByRole("button", { name: "Create your first app" }).click();
await p.getByLabel("App name").fill("Catrot");
await p.getByRole("button", { name: "Create app" }).click();
await p.waitForURL(/\/apps\//);
await p.getByRole("button", { name: "Add account" }).first().click();
await p.getByLabel("Public profile URL").fill("youtube.com/@catrot");
await p.getByText("Data source not set up").waitFor();
await p.screenshot({ path: `${out}/real_2_unconfigured.png` });
await p.getByRole("button", { name: "Connect account" }).click();
await p.getByText("Account added").waitFor({ timeout: 30000 });
await p.screenshot({ path: `${out}/real_3_added.png` });
await p.getByRole("button", { name: "Done" }).click();
await p.getByText("Data unavailable").first().waitFor();
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/real_4_app.png`, fullPage: true });
console.log("• unconfigured platform → Data unavailable");
console.log(errors.length ? `page errors: ${errors.join(" | ")}` : "• no page errors");
await b.close();
